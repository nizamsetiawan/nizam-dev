-- 1. TABEL PENGATURAN CMS UTAMA (Konfigurasi Dinamis Profil, Tampilan, Section, dll)
CREATE TABLE IF NOT EXISTS public.portfolio_settings (
    id TEXT PRIMARY KEY DEFAULT 'main_config',
    config JSONB NOT NULL DEFAULT '{}'::jsonb,
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- Aktifkan RLS dan izinkan akses baca & tulis
ALTER TABLE public.portfolio_settings ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Allow public read portfolio_settings" 
ON public.portfolio_settings FOR SELECT USING (true);

CREATE POLICY "Allow public insert/update portfolio_settings" 
ON public.portfolio_settings FOR ALL USING (true);


-- 2. TABEL PROYEK PORTOFOLIO
CREATE TABLE IF NOT EXISTS public.projects (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "Title" TEXT NOT NULL,
    "Description" TEXT,
    "Img" TEXT,
    "Link" TEXT,
    "Github" TEXT,
    "TechStack" TEXT[] DEFAULT ARRAY[]::TEXT[],
    "Features" TEXT[] DEFAULT ARRAY[]::TEXT[],
    is_published BOOLEAN DEFAULT TRUE,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

ALTER TABLE public.projects ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Allow public read projects" 
ON public.projects FOR SELECT USING (true);

CREATE POLICY "Allow public insert/update/delete projects" 
ON public.projects FOR ALL USING (true);


-- 3. TABEL SERTIFIKAT
CREATE TABLE IF NOT EXISTS public.certificates (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "Img" TEXT NOT NULL,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

ALTER TABLE public.certificates ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Allow public read certificates" 
ON public.certificates FOR SELECT USING (true);

CREATE POLICY "Allow public insert/delete certificates" 
ON public.certificates FOR ALL USING (true);


-- 4. TABEL BUKU TAMU / KOMENTAR PENGUNJUNG
CREATE TABLE IF NOT EXISTS public.portfolio_comments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_name TEXT NOT NULL,
    content TEXT NOT NULL,
    profile_image TEXT,
    is_pinned BOOLEAN DEFAULT FALSE,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

ALTER TABLE public.portfolio_comments ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Allow public read portfolio_comments" 
ON public.portfolio_comments FOR SELECT USING (true);

CREATE POLICY "Allow public insert/update/delete portfolio_comments" 
ON public.portfolio_comments FOR ALL USING (true);

-- Aktifkan Realtime untuk tabel Supabase (Settings, Projects, Certificates, Comments)
-- Memungkinkan perubahan di admin langsung tampil di halaman pengunjung secara otomatis tanpa reload
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_publication_tables 
    WHERE pubname = 'supabase_realtime' AND schemaname = 'public' AND tablename = 'portfolio_settings'
  ) THEN
    ALTER PUBLICATION supabase_realtime ADD TABLE public.portfolio_settings;
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM pg_publication_tables 
    WHERE pubname = 'supabase_realtime' AND schemaname = 'public' AND tablename = 'projects'
  ) THEN
    ALTER PUBLICATION supabase_realtime ADD TABLE public.projects;
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM pg_publication_tables 
    WHERE pubname = 'supabase_realtime' AND schemaname = 'public' AND tablename = 'certificates'
  ) THEN
    ALTER PUBLICATION supabase_realtime ADD TABLE public.certificates;
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM pg_publication_tables 
    WHERE pubname = 'supabase_realtime' AND schemaname = 'public' AND tablename = 'portfolio_comments'
  ) THEN
    ALTER PUBLICATION supabase_realtime ADD TABLE public.portfolio_comments;
  END IF;
END $$;


-- 5. TABEL LOG AKSES PENGUNJUNG (Visitor Analytics)
CREATE TABLE IF NOT EXISTS public.visitor_logs (
    id TEXT PRIMARY KEY,
    ip TEXT,
    location TEXT,
    device TEXT,
    os TEXT,
    browser TEXT,
    screen TEXT,
    path TEXT,
    referrer TEXT,
    timestamp TIMESTAMPTZ DEFAULT NOW()
);

ALTER TABLE public.visitor_logs ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Allow public read visitor_logs" 
ON public.visitor_logs FOR SELECT USING (true);

CREATE POLICY "Allow public insert/delete visitor_logs" 
ON public.visitor_logs FOR ALL USING (true);


-- 6. TABEL PROFIL PENGGUNA (Otorisasi Role Admin Supabase Auth)
CREATE TABLE IF NOT EXISTS public.profiles (
    id UUID REFERENCES auth.users ON DELETE CASCADE PRIMARY KEY,
    role TEXT DEFAULT 'admin',
    created_at TIMESTAMPTZ DEFAULT NOW()
);

ALTER TABLE public.profiles ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Allow public read profiles" 
ON public.profiles FOR SELECT USING (true);

CREATE POLICY "Allow user manage own profile" 
ON public.profiles FOR ALL USING (auth.uid() = id);


-- ==============================================================================
-- 7. PENYIMPANAN CLOUD (STORAGE BUCKETS) UNTUK GAMBAR
-- ==============================================================================
-- Membuat 4 storage bucket publik jika belum ada
INSERT INTO storage.buckets (id, name, public)
VALUES 
    ('project-images', 'project-images', true),
    ('certificate-images', 'certificate-images', true),
    ('profile-images', 'profile-images', true),
    ('resume-files', 'resume-files', true)
ON CONFLICT (id) DO NOTHING;

-- Kebijakan akses storage bucket publik (bisa dilihat siapa saja, bisa diunggah siapa saja)
CREATE POLICY "Public Access for project-images" 
ON storage.objects FOR SELECT 
USING (bucket_id = 'project-images');

CREATE POLICY "Public Upload for project-images" 
ON storage.objects FOR INSERT 
WITH CHECK (bucket_id = 'project-images');

CREATE POLICY "Public Access for certificate-images" 
ON storage.objects FOR SELECT 
USING (bucket_id = 'certificate-images');

CREATE POLICY "Public Upload for certificate-images" 
ON storage.objects FOR INSERT 
WITH CHECK (bucket_id = 'certificate-images');

CREATE POLICY "Public Access for profile-images" 
ON storage.objects FOR SELECT 
USING (bucket_id = 'profile-images');

CREATE POLICY "Public Upload for profile-images" 
ON storage.objects FOR INSERT 
WITH CHECK (bucket_id = 'profile-images');

CREATE POLICY "Public Access for resume-files" 
ON storage.objects FOR SELECT 
USING (bucket_id = 'resume-files');

CREATE POLICY "Public Upload for resume-files" 
ON storage.objects FOR INSERT 
WITH CHECK (bucket_id = 'resume-files');

-- Mengaktifkan RLS untuk tabel public.voters jika ada (untuk menghilangkan peringatan PostgREST)
DO $$
BEGIN
  IF EXISTS (SELECT FROM pg_tables WHERE schemaname = 'public' AND tablename = 'voters') THEN
    EXECUTE 'ALTER TABLE public.voters ENABLE ROW LEVEL SECURITY;';
    IF NOT EXISTS (
      SELECT 1 FROM pg_policies WHERE tablename = 'voters' AND policyname = 'Public Read voters'
    ) THEN
      EXECUTE 'CREATE POLICY "Public Read voters" ON public.voters FOR SELECT USING (true);';
    END IF;
  END IF;
END $$;
